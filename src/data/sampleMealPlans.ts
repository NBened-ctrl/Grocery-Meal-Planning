export const DEFAULT_WEEKLY_MEAL_PLAN: MealRecipe[] = WEEKLY_MEAL_PLAN_VARIANTS[0];

export function getScaledWeeklyMealPlan(
  variantIndex: number,
  adults: number = 2,
  kids: number = 2,
  month: string = 'August'
): { meals: MealRecipe[]; totalCost: number; summary: string } {
  const safeIndex = Math.abs(variantIndex) % WEEKLY_MEAL_PLAN_VARIANTS.length;
  const basePlan = WEEKLY_MEAL_PLAN_VARIANTS[safeIndex];
  const totalPeople = adults + kids;
  const portionScale = Math.max(0.75, (adults * 1.0 + kids * 0.5) / 3.0);
  const ts = Date.now();

  const scaledMeals: MealRecipe[] = basePlan.map((meal, idx) => ({
    ...meal,
    id: `meal-p${safeIndex}-${meal.dayOfWeek.toLowerCase()}-${ts}-${idx}`,
    servings: totalPeople,
    estimatedCostTotal: Number((meal.estimatedCostTotal * portionScale).toFixed(2)),
    costPerServing: Number(((meal.estimatedCostTotal * portionScale) / totalPeople).toFixed(2)),
    ingredients: meal.ingredients.map(ing => ({
      ...ing,
      estimatedPrice: ing.estimatedPrice ? Number((ing.estimatedPrice * (ing.isPantryStaple ? 1 : portionScale)).toFixed(2)) : undefined,
    })),
  }));

  const totalCost = Number(scaledMeals.reduce((sum, m) => sum + m.estimatedCostTotal, 0).toFixed(2));
  const planNames = scaledMeals.slice(0, 3).map(m => m.title.split(' with ')[0]).join(', ');
  const summary = `Generated fresh 7-day Waterloo dinner plan (${adults} Adults, ${kids} Kids) for ${month}: featuring ${planNames} & more!`;

  return { meals: scaledMeals, totalCost, summary };
}

